/** the wall's lettered things (the mug and the books; the pot of roses),
 *  where a night painting's lettering must give way to the mock's */
const LETTERED = [[586, 386, 962, 520, 10], [1356, 390, 1496, 524, 10]];
const lettered = (x, y) => {
  let z = 0;
  for (const [x0, y0, x1, y1, f] of LETTERED) {
    const d = Math.hypot(Math.max(x0 - x, 0, x - x1), Math.max(y0 - y, 0, y - y1));
    z = Math.max(z, d >= f ? 0 : 1 - (d / f) ** 2 * (3 - (2 * d) / f));
  }
  return z;
};
// the scale (sigma, px) below which the mock's detail is taken, by night
const NIGHT_BAND = 2.5;
/** a box blur (radius `r`, two passes, edges clamped) of a W x H field */
const boxBlur = (f, r) => {
  const pass = (src, dx) => {
    const out = new Float32Array(src.length);
    const [n, len] = dx ? [H, W] : [W, H];
    for (let k = 0; k < n; k++) {
      const at = (j) => src[dx ? k * W + Math.min(len - 1, Math.max(0, j)) : Math.min(len - 1, Math.max(0, j)) * W + k];
      let sum = 0;
      for (let j = -r; j <= r; j++) sum += at(j);
      for (let j = 0; j < len; j++) {
        out[dx ? k * W + j : j * W + k] = sum / (2 * r + 1);
        sum += at(j + r + 1) - at(j - r);
      }
    }
    return out;
  };
  return pass(pass(pass(pass(f, 1), 1), 0), 0);
};
const detail = async (finish) => {
  const day = finish === "day";
  const srcs = [raw(`plate-core-${finish}`), raw(`wall-reg-${finish}`), ORIGINAL, ...(day ? [] : [raw("plate-core-day"), raw("wall-reg-day")]), import.meta.filename];
  if (!srcs.every(existsSync) || !stale(raw(`plate-detail-${finish}`), srcs)) return;
  const rgba = (f) => sharp(f).resize(W, H, { fit: "fill" }).ensureAlpha().raw().toBuffer();
  const [core, wall, mock, coreD, wallD, clip] = await Promise.all([rgba(srcs[0]), rgba(srcs[1]), rgba(ORIGINAL), day ? null : rgba(srcs[3]), day ? null : rgba(srcs[4]), wallClip()]);
  /** the page's picture: the wall over the plate, its clip applied */
  const compose = (p, w) => {
    const out = new Float32Array(W * H * 3);
    for (let i = 0; i < W * H; i++) {
      const a = (w[i * 4 + 3] / 255) * (clip[i] / 255);
      for (let c = 0; c < 3; c++) out[i * 3 + c] = p[i * 4 + c] * (1 - a) + w[i * 4 + c] * a;
    }
    return out;
  };
  const here = compose(core, wall);
  // By night: the tone the finish keeps over the day's, per channel, soft;
  // the mock's pixels under it (`graded`), and what is kept of the night's own
  // painting (its moon, its lit windows, its glow: the broad band, `lowHere`)
  const low = (f32, sigma) => sharp(Buffer.from(f32.map((v) => Math.round(v))), { raw: { width: W, height: H, channels: 3 } }).blur(sigma).raw().toBuffer();
  let grade = null, graded = null, lowHere = null, lowGraded = null, gain = null;
  if (!day) {
    const [lh, lt] = await Promise.all([low(here, 8), low(compose(coreD, wallD), 8)]);
    grade = Float32Array.from(lh, (v, i) => Math.min(2, Math.max(0.2, v / Math.max(1, lt[i]))));
    graded = Float32Array.from({ length: W * H * 3 }, (_, i) => Math.min(255, mock[((i / 3) | 0) * 4 + (i % 3)] * grade[i]));
    [lowHere, lowGraded] = await Promise.all([low(here, NIGHT_BAND), low(graded, NIGHT_BAND)]);
    // The night is not the day's contrast scaled: a moonlit painting keeps
    // its detail's contrast (about 1.4 to 2 times what the day's, scaled by
    // the tone, would have). The mock's detail is laid in at the contrast of
    // the painting's own, region by region (the ratio of the two details'
    // local energy), so it is the mock's shapes at the night's weight.
    const energy = (hi) => {
      const sq = new Float32Array(W * H);
      for (let i = 0; i < W * H; i++) sq[i] = (hi(i * 3) ** 2 + hi(i * 3 + 1) ** 2 + hi(i * 3 + 2) ** 2) / 3;
      return boxBlur(sq, 10);
    };
    const [eHere, eGraded] = [energy((j) => here[j] - lowHere[j]), energy((j) => graded[j] - lowGraded[j])];
    gain = Float32Array.from(eHere, (v, i) => Math.min(3, Math.max(0.8, Math.sqrt((v + 25) / (eGraded[i] + 25)))));
  }
  // what the page's scene is, wherever it is the mock's: by day the mock's
  // pixel; by night its fine detail on the painting's own broad tone (and
  // where the wall's lettering is, on the mock's own: the painting's lettering
  // is a pixel or two off it, and would double it)
  const target = new Float32Array(W * H * 3);
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++) {
      const i = y * W + x;
      const z = day ? 0 : lettered(x + 0.5, y + 0.5);
      for (let c = 0; c < 3; c++) target[i * 3 + c] = day ? mock[i * 4 + c] : gain[i] * (graded[i * 3 + c] - lowGraded[i * 3 + c]) + z * lowGraded[i * 3 + c] + (1 - z) * lowHere[i * 3 + c];
    }
  const plate = Buffer.alloc(W * H * 3);
  const sprite = Buffer.from(wall);
  const clamp = (v) => Math.max(0, Math.min(255, Math.round(v)));
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++) {
      const i = y * W + x;
      const w = open(x + 0.5, y + 0.5);
      const a = wall[i * 4 + 3] / 255;
      const shown = a * (clip[i] / 255);
      for (let c = 0; c < 3; c++) {
        const d = w * (target[i * 3 + c] - here[i * 3 + c]);
        plate[i * 3 + c] = clamp(core[i * 4 + c] + (1 - shown) * d);
        // pixels the wall does not cover carry the plate's, a clean edge to resample
        sprite[i * 4 + c] = a < 0.01 ? plate[i * 3 + c] : clamp(wall[i * 4 + c] + (clip[i] ? 2 - shown : 1) * d);
      }
    }
  await mugFront(finish, mock, target);
  mkdirSync(`${RAW}/plate-detail-${finish}`, { recursive: true });
  mkdirSync(`${RAW}/wall-detail-${finish}`, { recursive: true });
  await Promise.all([
    sharp(plate, { raw: { width: W, height: H, channels: 3 } }).png().toFile(raw(`plate-detail-${finish}`)),
    sharp(sprite, { raw: { width: W, height: H, channels: 4 } }).png().toFile(raw(`wall-detail-${finish}`)),
  ]);
};

