/* ---------- the plate: raws this recipe derives from others ----------
   Each is rebuilt when a source is newer, so a regeneration carries
   through. The sky layer of a finish (layer-sky-<f>) is made in two steps.
   1. Its core, the mock's 1672 x 941 frame (plate-core-<f>): the plate with
      the page painted out (plate-open-<f>), its upper middle taken from an
      edit of it left bare plaster (plaster-<f>-b: no rose or vine under the
      masthead's words or behind the window), and the five lettered props in
      its margins laid back in from the original mock itself, over an edit
      that paints them out (props-out-<f>), since every edit of the plate
      redrew their lettering. By night a prop is the original's pixels
      through the colour map the moonlit plate applies to the day's there.
   2. The bleed: the core painted on BLEED mock px either side and below
      (TAKES, art/prompts/garden/<take>.txt), the core pasted back over it
      exact, feathered into it at its sides and foot. */
const RAW = "art/raw/garden";
const raw = (name) => `${RAW}/${name}/${name}.png`;
