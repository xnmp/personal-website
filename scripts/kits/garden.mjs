// Natural Garden (art/briefs/garden.md): a cottage garden in soft daylight,
// painted as a botanical watercolour, its page set on cream cards against
// a low stone wall. Raws in art/raw/garden; prompts in art/prompts/garden.
//
// The scene is one painted plate per finish (the original mock with its UI
// painted out; the wall above the window left bare plaster for the
// masthead's words; the low wall taken out too: it stands against the
// page, so it is a sprite of its own, `wall-*`, that the page lays behind
// the cards), painted on past the mock's edges (the bleed) so it registers
// with the page at any aspect. Night is the same garden under a full moon,
// generated as an edit of the day plate, so the two register. The surfaces
// were generated by day only: by night the cards, buttons and labels are
// graded from the day's (`gain`, MOON), the same paper by moonlight.
//
// Wherever the mock's own pixels are what the page shows (everything outside
// the page's own copy, window, stone and cards), the scene is the mock's
// fine detail itself: the plate and the wall sprite carry its lettering,
// petals and stone grain, not a regeneration's (detail(), below), and each
// finished plate frame is sharpened once, lightly (SHARPEN), against the
// kit's resampling. The two buttons, the "Projects" stone, the brand's leaf
// and the mug's rim in front of the window are cut from the mock too
// (buttons(), plaque(), brandLeaf(), mugFront()): no prompt, only the
// original (art/raw/originals/garden.png).

