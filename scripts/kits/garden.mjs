/** how far the mock's pixel is the page's scene: 1 clear of everything
 *  the page draws, easing to 0 at its edge (a box's feather is one width, or
 *  one per side: left, top, right, bottom) */
const open = (x, y) => {
  let w = 1;
  for (const [x0, y0, x1, y1, f] of EXCLUDED) {
    const [fl, ft, fr, fb] = Array.isArray(f) ? f : [f, f, f, f];
    const d = Math.hypot(Math.max(x0 - x, 0, x - x1) / (x < x0 ? fl : fr), Math.max(y0 - y, 0, y - y1) / (y < y0 ? ft : fb));
    if (d < 1) w = Math.min(w, d * d * (3 - 2 * d));
  }
  return w;
};
