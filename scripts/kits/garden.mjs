const TAKES = { day: "plate-bleed-day-c", night: "plate-bleed-night" };
// an unsharp mask: the painting plus `amount` of its difference from its blur
const SHARPEN = { amount: 0.9, sigma: 1 };
const stale = (out, srcs) => !existsSync(out) || srcs.some((src) => statSync(out).mtimeMs < statSync(src).mtimeMs);
const rgb = (file, w = W, h = H) => sharp(file).resize(w, h, { fit: "fill" }).removeAlpha().raw().toBuffer();
const write = async (name, buf, w = W, h = H) => {
  mkdirSync(`${RAW}/${name}`, { recursive: true });
  await sharp(buf, { raw: { width: w, height: h, channels: 3 } }).png().toFile(raw(name));
};

/** a weight inside a box [x0, y0, x1, y1], easing up from each edge over
 *  [left, top, right, bottom] px; an edge on the frame's stays hard */
const inside =
  ([x0, y0, x1, y1], [fl, ft, fr, fb]) =>
  (x, y) => {
    if (x < x0 || x > x1 || y < y0 || y > y1) return 0;
    const ease = (d, f) => (f <= 0 || d >= f ? 1 : 0.5 - 0.5 * Math.cos((Math.PI * d) / f));
    return ease(x - x0, x0 <= 0 ? 0 : fl) * ease(y - y0, y0 <= 0 ? 0 : ft) * ease(x1 - x, x1 >= W - 1 ? 0 : fr) * ease(y1 - y, y1 >= H - 1 ? 0 : fb);
  };

/** Lays `src` into `dst` (W x H RGB, in place) as the standard seamless
 *  composite does, in two bands: its detail over the narrow feather `fine`,
 *  its broad tone over the wide `broad`, so a region a shade lighter or
 *  warmer than the plate grades into it rather than standing as a patch.
 *  `shift` takes the source from that many px to the left (a clone). */
const SIGMA = 18;
const lay = async (dst, src, fine, broad, shift = 0) => {
  const low = (b) => sharp(b, { raw: { width: W, height: H, channels: 3 } }).blur(SIGMA).raw().toBuffer();
  const [ld, ls] = await Promise.all([low(dst), low(src)]);
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++) {
      const [wf, wb] = [fine(x, y), broad(x, y)];
      if (!wf && !wb) continue;
      const [i, j] = [(y * W + x) * 3, (y * W + Math.max(0, x - shift)) * 3];
      for (let k = 0; k < 3; k++) {
        const lo = ld[i + k] * (1 - wb) + ls[j + k] * wb;
        const hi = (dst[i + k] - ld[i + k]) * (1 - wf) + (src[j + k] - ls[j + k]) * wf;
        dst[i + k] = Math.max(0, Math.min(255, Math.round(lo + hi)));
      }
    }
};

/** The plate's dappled leaf shadows (the model's, in plate-open) are crisper
 *  and darker than the mock's soft shading of the plaster. In `box` (eased
 *  in over `fade` px), the mid band of tone (blur 3 minus blur 28) is held to
 *  `k` of its strength; the broad shading and the grain are left. */
const soften = async (buf, box, fade, k) => {
  const blur = (sigma) => sharp(buf, { raw: { width: W, height: H, channels: 3 } }).blur(sigma).raw().toBuffer();
  const [fine, broad] = await Promise.all([blur(3), blur(28)]);
  const w = inside(box, [fade, fade, fade, fade]);
  for (let y = box[1]; y <= box[3]; y++)
    for (let x = box[0]; x <= box[2]; x++) {
      const a = w(x, y) * (1 - k);
      if (!a) continue;
      const i = (y * W + x) * 3;
      for (let c = 0; c < 3; c++) buf[i + c] = Math.max(0, Math.min(255, Math.round(buf[i + c] - a * (fine[i + c] - broad[i + c]))));
    }
};

