/** a prop's matte (W x H, one channel), its edge softened a pixel, and its
 *  bounding box */
const matte = async ({ polys, holes = [], foot }) => {
  const d = (ps) => ps.map((p) => `M${p.map((q) => q.join(",")).join(" L")} Z`).join(" ");
  const svg = `<svg width="${W}" height="${H}" xmlns="http://www.w3.org/2000/svg"><rect width="${W}" height="${H}"/><path d="${d(polys)}" fill="#fff"/>${holes.length ? `<path d="${d(holes)}"/>` : ""}</svg>`;
  const m = await sharp(Buffer.from(svg)).blur(1.1).extractChannel(0).raw().toBuffer();
  if (foot) {
    const [y0, y1] = foot;
    for (let y = y0; y < H; y++) {
      const f = y >= y1 ? 0 : 1 - ((y - y0) / (y1 - y0)) ** 1.5;
      for (let x = 0; x < W; x++) m[y * W + x] = Math.round(m[y * W + x] * f);
    }
  }
  let [x0, y0, x1, y1] = [W, H, -1, -1];
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) if (m[y * W + x] > 2) [x0, y0, x1, y1] = [Math.min(x0, x), Math.min(y0, y), Math.max(x1, x), Math.max(y1, y)];
  return { m, box: [x0, y0, x1, y1] };
};

/** the affine colour map (3 x [r g b 1]) taking `from` to `to` where the
 *  matte is solid: least squares, by the normal equations */
const colourMap = (from, to, { m, box: [x0, y0, x1, y1] }) => {
  const A = Array.from({ length: 4 }, () => new Float64Array(4));
  const B = Array.from({ length: 3 }, () => new Float64Array(4));
  for (let y = y0; y <= y1; y++)
    for (let x = x0; x <= x1; x++) {
      if (m[y * W + x] <= 200) continue;
      const i = (y * W + x) * 3;
      const v = [from[i], from[i + 1], from[i + 2], 255];
      for (let r = 0; r < 4; r++) {
        for (let c = 0; c < 4; c++) A[r][c] += v[r] * v[c];
        for (let k = 0; k < 3; k++) B[k][r] += v[r] * to[i + k];
      }
    }
  const solve = (b) => {
    const a = A.map((row, r) => [...row, b[r]]);
    for (let c = 0; c < 4; c++) {
      const p = a.reduce((best, _, r) => (r >= c && Math.abs(a[r][c]) > Math.abs(a[best][c]) ? r : best), c);
      [a[c], a[p]] = [a[p], a[c]];
      for (let r = 0; r < 4; r++) if (r !== c) for (let k = 4, f = a[r][c] / a[c][c]; k >= c; k--) a[r][k] -= f * a[c][k];
    }
    return a.map((row, r) => row[4] / row[r]);
  };
  return B.map(solve);
};

/* ---------- the vine's right end, by day ----------
   The mock's vine runs on past the nav's first word (x 1008-1068, behind the
   word "index"), so it is cut short. A fade (the first cut) leaves a feathered
   ruler line; a straight cut a step of tone (the leaves shade the plaster
   round them, the plate's plaster beyond is lighter). So the cut is a path
   down the plaster between the leaves (the cheapest of those that keep to
   x 970-1032, a pixel a row: dynamic programming over how far each pixel
   stands from the plaster), and what is laid past x 960 is only the leaves
   and roses themselves (alpha from that distance, the colour what the plaster
   leaves of them), over the plate's plaster. The mock's grey shade behind the
   vine, above the window, stays out of them: it would end in a hard line at
   the window's edge, which a tablet's crop shows. */
const PLASTER = [232, 214, 194];
const smooth = (t) => (t <= 0 ? 0 : t >= 1 ? 1 : t * t * (3 - 2 * t));
/** how much of a pixel is leaf or petal: how far its hue stands from the
 *  plaster's (green or pink, where the cream's red - green and green - blue
 *  are both about 20), or how dark it is (a leaf's shade); the plaster's own
 *  shadow, a darker cream, is not */
const leafAlpha = (rgb, i) => {
  const [r, g, b] = [rgb[i], rgb[i + 1], rgb[i + 2]];
  const chroma = Math.hypot(r - g - (PLASTER[0] - PLASTER[1]), g - b - (PLASTER[1] - PLASTER[2]));
  return Math.max(smooth((chroma - 20) / 24), smooth((120 - (0.299 * r + 0.587 * g + 0.114 * b)) / 40));
};
/** x of the cut at each row 0-70: 1022 above y 20, where the top leaf's tip
 *  reaches past the cut, then the cheapest path down to the window's edge */
const vineEnd = (rgb) => {
  const [y0, y1, x0, x1] = [24, 70, 970, 1032];
  const n = x1 - x0 + 1;
  // clear of the word: "index" starts at x 1012 (halo and all, 1000) and its
  // letters stand from y 27 to 42
  const cost = (j, i) => (y0 + j < 46 && x0 + i > 994 ? Infinity : leafAlpha(rgb, ((y0 + j) * W + x0 + i) * 3) + 0.002 * Math.abs(x0 + i - 1000));
  const best = [Float64Array.from({ length: n }, (_, i) => cost(0, i))];
  const from = [new Int16Array(n)];
  for (let j = 1; j <= y1 - y0; j++) {
    const [b, f] = [new Float64Array(n).fill(Infinity), new Int16Array(n)];
    for (let i = 0; i < n; i++)
      for (const di of [-1, 0, 1]) {
        const v = best[j - 1][i + di] + cost(j, i) + 0.01 * Math.abs(di);
        if (v < b[i]) [b[i], f[i]] = [v, i + di];
      }
    best.push(b);
    from.push(f);
  }
  const path = new Float64Array(y1 + 1).fill(1022);
  let i = best[y1 - y0].indexOf(Math.min(...best[y1 - y0]));
  for (let j = y1 - y0; j >= 0; j--) [path[y0 + j], i] = [x0 + i, from[j][i]];
  for (let y = 20; y < y0; y++) path[y] = 1022 + ((path[y0] - 1022) * (y - 20)) / (y0 - 20);
  return path;
};
/** Lays the leaves of `src` inside `box` over `dst`, left of the cut `end[y]`
 *  (a pixel and a half of ease), the plaster they stand on left to `dst`;
 *  where `placed` (a weight) has already laid the picture itself, they are
 *  not laid again. */
const layLeaves = (dst, src, [x0, y0, x1, y1], end, placed = () => 0) => {
  for (let y = y0; y <= y1; y++) {
    const foot = Math.min(1, y1 + 1 - y);
    for (let x = x0; x <= x1; x++) {
      const i = (y * W + x) * 3;
      const [a, keep] = [leafAlpha(src, i), foot * smooth((end[y] - x + 1.5) / 3) * (1 - placed(x, y))];
      if (a * keep < 0.004) continue;
      for (let c = 0; c < 3; c++) {
        // the leaf's own colour (the plaster unmixed from the pixel), over the plate's
        const leaf = Math.max(0, Math.min(255, (src[i + c] - (1 - a) * PLASTER[c]) / Math.max(a, 0.05)));
        dst[i + c] = Math.round(dst[i + c] + keep * a * (leaf - dst[i + c]));
      }
    }
  }
};

const core = async (finish) => {
  const name = `plate-core-${finish}`;
  const srcs = [raw(`plate-open-${finish}`), raw(`plaster-${finish}-b`), raw(`props-out-${finish}`), ORIGINAL, raw("plate-open-day")];
  if (!srcs.every(existsSync) || !stale(raw(name), [...srcs, import.meta.filename])) return;
  const [open, plaster, cleared, original, openDay] = await Promise.all(srcs.map((f) => rgb(f)));
  const out = Buffer.from(open);
  // the bare plaster over the upper middle (x 690-1352, where both are plain
  // plaster at its sides), its own rose vine at the right end first cloned
  // out with its plaster from 150 px to the left
  const patched = Buffer.from(plaster);
  const vine = [1240, 0, 1356, 200];
  await lay(patched, plaster, inside(vine, [14, 0, 6, 14]), inside(vine, [50, 0, 10, 50]), 150);
  const upper = [690, 0, 1352, 350];
  await lay(out, patched, inside(upper, [20, 0, 6, 20]), inside(upper, [60, 0, 14, 60]));
  // The vine and its roses over the top edge, from the nav's left to the
  // window's corner: the plaster above took them out with the masthead's
  // words (x 1082+, which stay out). By day the mock's own; by night the
  // night plate's.
  // It must end clear of the nav's first word: by day (the light rice) that
  // starts at x 1008, so the vine stops at x 1004; by night the longest rice
  // name ("cosmic dusk") starts it at x 954, so it stops short of the big
  // rose (x 905-967), which would sit behind the "i" of "index". It ends on
  // the vine's own gaps, not on a feathered ruler line (below). The plaster
  // under it eases out into the plate's before the window's top edge (y 71),
  // as it must where the window does not stand over the seam (a tablet's
  // crop); the leaves themselves run on to the edge, where the mock's touch it.
  if (finish === "day") {
    // the mock's plaster, tone and detail, as far as the roses (x 960) ...
    const reach = [690, 0, 960, 66];
    const fine = inside(reach, [26, 0, 36, 16]);
    await lay(out, original, fine, inside(reach, [44, 0, 76, 30]));
    // ... and past them, and below where the plaster eases out, only its
    // leaves, laid over the plate's plaster, so the cut carries no step of
    // tone: the vine cut along a path down its own gaps
    layLeaves(out, original, [690, 0, 1030, 70], vineEnd(original), fine);
  } else {
    const arch = [690, 0, 906, 66];
    await lay(out, open, inside(arch, [26, 0, 18, 16]), inside(arch, [44, 0, 40, 30]));
  }
  // the plate's leaf shadows on the plaster beside the headline and behind
  // the nav's words, as soft as the mock's
  await soften(out, [380, 0, 700, 400], 40, 0.2);
  // The plate's own bush right of "Try it live" rises 70 px above the mock's
  // (the mock has bare plaster there down to y 343): the plaster 118 px above
  // it is laid over it, so where the page shows the plate (the headline's
  // column) there is no bush, and where it shows the mock (detail(), x 641 on)
  // the two grade into each other as plaster.
  const bush = [628, 258, 700, 348];
  const above = Buffer.from(out);
  for (let y = bush[1]; y <= bush[3]; y++) out.copy(above, (y * W + bush[0]) * 3, ((y - 118) * W + bush[0]) * 3, ((y - 118) * W + bush[2] + 1) * 3);
  await lay(out, above, inside(bush, [16, 16, 0, 12]), inside(bush, [30, 30, 0, 24]));
  await soften(out, [996, 0, 1352, 74], 24, 0.3);
  for (const prop of Object.values(PROPS)) {
    const cut = await matte(prop);
    const [x0, y0, x1, y1] = cut.box;
    const clear = [x0 - 16, y0 - 16, x1 + 16, y1 + 16];
    await lay(out, cleared, inside(clear, [12, 12, 12, 12]), inside(clear, [40, 40, 40, 40]));
    const map = finish === "day" ? null : colourMap(openDay, open, cut);
    for (let y = y0; y <= y1; y++)
      for (let x = x0; x <= x1; x++) {
        const a = cut.m[y * W + x] / 255;
        if (!a) continue;
        const i = (y * W + x) * 3;
        const c = [original[i], original[i + 1], original[i + 2]];
        for (let k = 0; k < 3; k++) {
          const v = map ? map[k][0] * c[0] + map[k][1] * c[1] + map[k][2] * c[2] + map[k][3] * 255 : c[k];
          out[i + k] = Math.max(0, Math.min(255, Math.round(out[i + k] * (1 - a) + v * a)));
        }
      }
  }
  await write(name, out);
};

const sky = async (finish) => {
  const name = `layer-sky-${finish}`;
  const srcs = [raw(TAKES[finish]), raw(`plate-detail-${finish}`), import.meta.filename];
  if (!srcs.every(existsSync) || !stale(raw(name), srcs)) return;
  const [BW, BH] = [W + 2 * BLEED, H + BLEED];
  const [out, c] = await Promise.all([rgb(srcs[0], BW, BH), rgb(srcs[1])]);
  // the core exact, eased in from its sides and foot over FEATHER px (its
  // top is the frame's)
  const FEATHER = 24;
  const ease = (d) => (d >= FEATHER ? 1 : 0.5 - 0.5 * Math.cos((Math.PI * Math.max(0, d)) / FEATHER));
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++) {
      const a = ease(Math.min(x, W - 1 - x, H - 1 - y));
      const [i, o] = [(y * W + x) * 3, (y * BW + x + BLEED) * 3];
      for (let k = 0; k < 3; k++) out[o + k] = Math.round(out[o + k] * (1 - a) + c[i + k] * a);
    }
  // Sharpened once, over the whole painting: the page shows it through two
  // resamplings (build-kit.mjs frames it at 2654 px for 2312 and the browser
  // scales it back) and a q78 encode, which took the plate to 40-50% of the
  // mock's edge energy (Laplacian variance) at 1:1; this gives it back
  // (measured 95-110%, the wall's detail alone being 100% unsharpened).
  const low = await sharp(out, { raw: { width: BW, height: BH, channels: 3 } }).blur(SHARPEN.sigma).raw().toBuffer();
  for (let i = 0; i < out.length; i++) out[i] = Math.max(0, Math.min(255, Math.round(out[i] + SHARPEN.amount * (out[i] - low[i]))));
  await write(name, out, BW, BH);
};

/* ---------- the wall, laid back on the mock ----------
   The wall sprite (wall-<f>, the mock's low wall and what stands on its
   ledge, drawn by the model in the plate's frame) holds its things only
   roughly where the mock has them: the mug 8 px left of it, the books 7 and
   the cat 8 px right, the potted rose 20 (a stretch that grows along the
   ledge), all a few px high. The page lays it between the window and the
   cards, so it is re-registered: for blocks on the ledge, between the window's foot
   and the cards' top (and the rose's column), the displacement that lays
   the sprite on the picture it should match is found (zero-mean SSD), and
   the sprite is warped by the field those give, smoothed. Day matches the
   mock; night matches the day's registered wall (a night edit of it). */
const SPRITE_ZONES = [[420, 575, 300, 1530], [280, 500, 1360, 1500]]; // y0, y1, x0, x1
const alphaOf = (png) => sharp(png).resize(W, H, { fit: "fill" }).ensureAlpha().extractChannel(3).raw().toBuffer();
const greyOf = (png) => sharp(png).resize(W, H, { fit: "fill" }).greyscale().raw().toBuffer();
/** the sprite's displacement samples [x, y, dx, dy] against `ref` (grey): the sprite's content at (x + dx, y + dy) is what the ref has at (x, y) */
const displacements = (ref, flat, alpha, accept) => {
  const [bs, step, R] = [40, 16, 36];
  const out = [];
  for (const [zy0, zy1, zx0, zx1] of SPRITE_ZONES)
    for (let y = zy0; y + bs <= zy1; y += step)
      for (let x = zx0; x + bs <= zx1; x += step) {
        // only where the sprite itself is, and the ref has something to match
        let cover = 0, mean = 0, spread = 0;
        for (let j = 0; j < bs; j += 4) for (let i = 0; i < bs; i += 4) cover += alpha[(y + j) * W + x + i];
        if (cover / (bs / 4) ** 2 < 235) continue;
        for (let j = 0; j < bs; j += 2) for (let i = 0; i < bs; i += 2) mean += ref[(y + j) * W + x + i];
        mean /= (bs / 2) ** 2;
        for (let j = 0; j < bs; j += 2) for (let i = 0; i < bs; i += 2) spread += (ref[(y + j) * W + x + i] - mean) ** 2;
        spread = Math.sqrt(spread / (bs / 2) ** 2);
        if (spread < 8) continue;
        let best = [Infinity, 0, 0];
        for (let dy = -R; dy <= R; dy++)
          for (let dx = -R; dx <= R; dx++) {
            if (y + dy < 0 || x + dx < 0 || y + dy + bs > H || x + dx + bs > W) continue;
            let m = 0;
            for (let j = 0; j < bs; j += 2) for (let i = 0; i < bs; i += 2) m += flat[(y + j + dy) * W + x + i + dx];
            m /= (bs / 2) ** 2;
            let sum = 0;
            for (let j = 0; j < bs; j += 2) for (let i = 0; i < bs; i += 2) {
              const d = ref[(y + j) * W + x + i] - mean - (flat[(y + j + dy) * W + x + i + dx] - m);
              sum += d * d;
            }
            if (sum < best[0]) best = [sum, dx, dy];
          }
        if (Math.sqrt(best[0] / (bs / 2) ** 2) / spread < accept) out.push([x + bs / 2, y + bs / 2, best[1], best[2]]);
      }
  // a sample far from its neighbours' median is a false match
  return out.filter((p) => {
    const near = out.filter((o) => o !== p && Math.hypot(o[0] - p[0], o[1] - p[1]) < 75);
    if (near.length < 3) return true;
    const med = (k) => near.map((o) => o[k]).sort((a, b) => a - b)[near.length >> 1];
    return Math.hypot(p[2] - med(2), p[3] - med(3)) < 6;
  });
};
/** the sprite (RGBA, W x H) resampled through the field the samples give (a Gaussian-weighted mean, on a 16 px grid, bilinear between) */
const warp = (sprite, samples) => {
  const [G, SIGMA2] = [16, 2 * 55 * 55];
  const [gw, gh] = [Math.ceil(W / G) + 1, Math.ceil(H / G) + 1];
  const grid = [new Float32Array(gw * gh), new Float32Array(gw * gh)];
  for (let j = 0; j < gh; j++)
    for (let i = 0; i < gw; i++) {
      let sw = 0, sx = 0, sy = 0, near = [Infinity, 0, 0];
      for (const [px, py, dx, dy] of samples) {
        const d2 = (px - i * G) ** 2 + (py - j * G) ** 2;
        if (d2 < near[0]) near = [d2, dx, dy];
        const w = Math.exp(-d2 / SIGMA2);
        sw += w; sx += w * dx; sy += w * dy;
      }
      [grid[0][j * gw + i], grid[1][j * gw + i]] = sw > 1e-3 ? [sx / sw, sy / sw] : [near[1], near[2]];
    }
  const at = (a, x, y) => {
    const [i, j] = [Math.min(gw - 2, Math.floor(x / G)), Math.min(gh - 2, Math.floor(y / G))];
    const [fx, fy, k] = [x / G - i, y / G - j, j * gw + i];
    return (a[k] * (1 - fx) + a[k + 1] * fx) * (1 - fy) + (a[k + gw] * (1 - fx) + a[k + gw + 1] * fx) * fy;
  };
  const out = Buffer.alloc(W * H * 4);
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++) {
      const [sx, sy] = [x + at(grid[0], x, y), y + at(grid[1], x, y)];
      const [x0, y0] = [Math.floor(sx), Math.floor(sy)];
      const [fx, fy] = [sx - x0, sy - y0];
      const c = [0, 0, 0, 0];
      for (const [ox, oy, w] of [[0, 0, (1 - fx) * (1 - fy)], [1, 0, fx * (1 - fy)], [0, 1, (1 - fx) * fy], [1, 1, fx * fy]]) {
        const k = (Math.min(H - 1, Math.max(0, y0 + oy)) * W + Math.min(W - 1, Math.max(0, x0 + ox))) * 4;
        const a = sprite[k + 3] / 255; // bilinear in premultiplied colour
        c[0] += sprite[k] * a * w; c[1] += sprite[k + 1] * a * w; c[2] += sprite[k + 2] * a * w; c[3] += a * w;
      }
      const o = (y * W + x) * 4;
      out[o + 3] = Math.round(c[3] * 255);
      for (let k = 0; k < 3; k++) out[o + k] = c[3] > 0 ? Math.max(0, Math.min(255, Math.round(c[k] / c[3]))) : 0;
    }
  return out;
};

