/**
 * Generates src/app/rice.css from the author's actual dotfiles (chezmoi repo).
 * The site's themes ARE the terminal's themes — provenance, not decoration.
 *
 * Sources:
 *  - ~/.local/share/chezmoi/dot_config/wezterm/executable_wezterm.lua
 *      inline color_schemes (Cosmic Dusk, Rapture)
 *  - Horizon Dark (Gogh) — wezterm builtin, pinned here from
 *      https://github.com/Gogh-Co/Gogh/blob/master/themes/Horizon%20Dark.yml
 *  - ~/.local/share/chezmoi/dot_config/hypr/executable_hyprland.conf
 *      rounding, border width, active-border gradient
 *
 * Run manually after changing the rice: `bun scripts/theme-from-dotfiles.mjs`
 * The output is committed so Vercel builds don't need the dotfiles.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const CHEZMOI = join(homedir(), ".local/share/chezmoi/dot_config");
const OUT = new URL("../src/app/rice.css", import.meta.url).pathname;

// ---------- helpers ----------

const hex = (h) => {
  const s = h.replace("#", "");
  return [0, 2, 4].map((i) => parseInt(s.slice(i, i + 2), 16));
};
const toHex = (rgb) =>
  "#" + rgb.map((v) => Math.round(Math.max(0, Math.min(255, v))).toString(16).padStart(2, "0")).join("");
/** blend a over b by t (0..1) */
const mix = (a, b, t) => toHex(hex(a).map((v, i) => v * t + hex(b)[i] * (1 - t)));
const alpha = (h, a) => `rgba(${hex(h).join(", ")}, ${a})`;

// ---------- parse wezterm inline schemes ----------

const lua = readFileSync(join(CHEZMOI, "wezterm/executable_wezterm.lua"), "utf8");

function parseScheme(name) {
  const start = lua.indexOf(`['${name}']`);
  if (start === -1) throw new Error(`scheme ${name} not found in wezterm.lua`);
  const block = lua.slice(start, lua.indexOf("},", lua.indexOf("brights", start)) + 1);
  const get = (key) => block.match(new RegExp(`${key}\\s*=\\s*'(#[0-9a-fA-F]{6})'`))?.[1];
  const list = (key) =>
    [...block.match(new RegExp(`${key}\\s*=\\s*\\{([^}]*)\\}`))[1].matchAll(/#[0-9a-fA-F]{6}/g)].map((m) => m[0]);
  return {
    background: get("background"),
    foreground: get("foreground"),
    selection: get("selection_bg"),
    ansi: list("ansi"),
    brights: list("brights"),
  };
}

const schemes = {
  // wezterm builtin — pinned from the Gogh source (see header).
  horizon: {
    background: "#1C1E26",
    foreground: "#FDF0ED",
    selection: "#232530",
    ansi: ["#16161C", "#E95678", "#29D398", "#FAB795", "#26BBD9", "#EE64AE", "#59E3E3", "#FADAD1"],
    brights: ["#232530", "#EC6A88", "#3FDAA4", "#FBC3A7", "#3FC6DE", "#F075B7", "#6BE6E6", "#FDF0ED"],
  },
  "cosmic-dusk": parseScheme("Cosmic Dusk"),
  rapture: parseScheme("Rapture"),
};

// ---------- parse hyprland geometry ----------

const hypr = readFileSync(join(CHEZMOI, "hypr/executable_hyprland.conf"), "utf8");
const rounding = hypr.match(/rounding\s*=\s*(\d+)/)?.[1] ?? "3";
const borderW = hypr.match(/border_size\s*=\s*(\d+)/)?.[1] ?? "2";
const grad = hypr.match(/col\.active_border\s*=\s*rgba\((\w{6})\w{2}\)\s*rgba\((\w{6})\w{2}\)\s*(\d+deg)/);
const gradient = grad
  ? `linear-gradient(${grad[3]}, #${grad[1]}, #${grad[2]})`
  : "linear-gradient(45deg, #33ccff, #00ff99)";

// ---------- map terminal scheme -> site tokens ----------

function tokens(s, dark = true) {
  const { background: bg, foreground: fg } = s;
  const [, red, green, yellow, , , cyan] = s.ansi;
  return {
    "--paper": bg,
    "--paper-warm": mix(fg, bg, 0.06),
    "--ink": mix(fg, bg, 0.92),
    "--ink-soft": mix(fg, bg, 0.55),
    "--rule": mix(fg, bg, 0.16),
    "--rust": red,
    "--amber": yellow,
    "--cyan": cyan,
    "--olive": green,
    "--code-bg": alpha(fg, 0.07),
    "--code-border": alpha(fg, 0.14),
    "--shadow": dark ? "rgba(0, 0, 0, 0.55)" : alpha(mix(fg, bg, 0.9), 0.25),
    "--overlay": alpha(bg, 0.65),
  };
}

// Light chassis: Horizon's ink and hues on near-white paper, accents darkened
// for contrast on light ground.
const light = {
  "--paper": "#fcfbf9",
  "--paper-warm": "#f4f2ee",
  "--ink": "#16161c",
  "--ink-soft": "#5c5f70",
  "--rule": "#e0ddd6",
  "--rust": mix("#E95678", "#000000", 0.85),
  "--amber": mix("#FAB795", "#000000", 0.62),
  "--cyan": mix("#26BBD9", "#000000", 0.78),
  "--olive": mix("#29D398", "#000000", 0.68),
  "--code-bg": "rgba(22, 22, 28, 0.05)",
  "--code-border": "rgba(22, 22, 28, 0.1)",
  "--shadow": "rgba(22, 22, 28, 0.22)",
  "--overlay": "rgba(252, 251, 249, 0.65)",
};

const block = (sel, t) =>
  `${sel} {\n${Object.entries(t).map(([k, v]) => `  ${k}: ${v};`).join("\n")}\n}`;

const css = `/* GENERATED by scripts/theme-from-dotfiles.mjs — do not hand-edit.
 * These themes are the author's actual terminal themes (chezmoi dotfiles).
 * paper = designed light chassis; the rest are the rice, verbatim. */

:root {
  --radius: ${rounding}px;
  --border-w: ${borderW}px;
  --active-grad: ${gradient};
}

${block(':root, :root[data-rice="paper"]', light)}

${block(':root[data-rice="horizon"]', tokens(schemes.horizon))}

${block(':root[data-rice="cosmic-dusk"]', tokens(schemes["cosmic-dusk"]))}

${block(':root[data-rice="rapture"]', tokens(schemes.rapture))}
`;

writeFileSync(OUT, css);
console.log(`wrote ${OUT}`);
console.log(`rounding=${rounding}px border=${borderW}px gradient=${gradient}`);
for (const [name, s] of Object.entries(schemes)) console.log(name, s.background, "->", s.foreground);
