// Additional upstream palettes are independent of the author's local dotfiles.
// Regenerate with: bun scripts/build-palettes.mjs
import { writeFileSync } from "node:fs";
import { EXTRA_PALETTES } from "./theme-palettes.mjs";
const blocks = Object.entries(EXTRA_PALETTES).map(([id, tokens]) =>
  `:root[data-rice="${id}"] {\n${Object.entries(tokens).map(([key, value]) => `  ${key}: ${value};`).join("\n")}\n}`,
);
writeFileSync(new URL("../src/app/palettes.css", import.meta.url),
  `/* Generated by scripts/build-palettes.mjs. Sources: scripts/theme-palettes.mjs. */\n\n${blocks.join("\n\n")}\n\n:root[data-rice-mode="light"] { color-scheme: light; }\n:root[data-rice-mode="dark"] { color-scheme: dark; }\n`);
